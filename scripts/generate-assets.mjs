/**
 * Generates derived image assets into public/ (outputs are committed):
 *   - responsive variants of the full-resolution originals in assets/images/
 *     into public/images/<dir>/ + a manifest at src/generated/images.js
 *     (render.js builds srcset from it). Originals are never deployed.
 *   - portrait hero crop of the floral dome, blurred desktop backdrop
 *   - og-image.jpg (1200x630 social / WhatsApp preview)
 *   - favicon.svg monogram + apple-touch-icon.png
 *
 * Run with:  npm run generate:assets
 */
import { readFile, writeFile, readdir, mkdir, stat, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import opentype from 'opentype.js';
import { archPath } from '../src/lib/arch.js';
import { content } from '../src/content.js';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pub = (...p) => path.join(root, 'public', ...p);
const srcImg = (...p) => path.join(root, 'assets/images', ...p);
// When the décor is a surprise, no venue render is written into public/ at all.
const VENUE = content.SHOW_VENUE_RENDERS !== false;

const GOLD = '#C9A45C';
const GOLD_LIGHT = '#E8CF9A';
const IVORY = '#FBF5EE';
const BLUSH = '#F3D9DC';

const loadFont = async (file) =>
  opentype.parse((await readFile(path.join(root, 'scripts/fonts', file))).buffer);

/* ---------- responsive variants ---------- */
const manifest = {};
const add = (key, info, file) => (manifest[key] ||= []).push({ w: info.width, h: info.height, src: `/images/${file}` });

async function variants() {
  const jobs = [
    ['couple', [640, 1080, 1600], 78],
    ...(VENUE ? [['venue', [640, 1080], 74]] : []),
  ];
  for (const [dir, widths, quality] of jobs) {
    const outDir = pub('images', dir);
    await rm(outDir, { recursive: true, force: true });
    await mkdir(outDir, { recursive: true });
    const files = (await readdir(srcImg(dir))).filter((f) => f.endsWith('.webp'));
    for (const f of files) {
      const src = srcImg(dir, f);
      const { width: origW } = await sharp(src).metadata();
      const base = f.replace('.webp', '');
      // never upscale: widths above the original collapse to the original width
      const ws = [...new Set(widths.map((w) => Math.min(w, origW)))];
      for (const w of ws) {
        const name = `${base}-${w}.webp`;
        const info = await sharp(src).resize({ width: w }).webp({ quality }).toFile(path.join(outDir, name));
        add(`${dir}/${base}`, info, `${dir}/${name}`);
      }
    }
  }
}

/* ---------- hero crop + desktop backdrop ---------- */
async function hero() {
  if (!VENUE) {
    await rm(pub('images/venue'), { recursive: true, force: true });
    return;
  }
  const src = srcImg('venue/floral-dome.webp');
  const { width, height } = await sharp(src).metadata();
  const cropW = Math.round(height * 0.72);
  const crop = await sharp(src)
    .extract({ left: Math.round((width - cropW) / 2), top: 0, width: cropW, height })
    .toBuffer();
  for (const w of [540, cropW]) {
    const name = `floral-dome-hero-${w}.webp`;
    const info = await sharp(crop).resize({ width: w }).webp({ quality: 64, effort: 6 }).toFile(pub('images/venue', name));
    add('venue/floral-dome-hero', info, `venue/${name}`);
  }
  await sharp(src)
    .resize({ width: 360 })
    .blur(16)
    .modulate({ brightness: 0.5, saturation: 1.1 })
    .webp({ quality: 50 })
    .toFile(pub('images/venue/backdrop.webp'));
}

async function writeManifest() {
  await mkdir(path.join(root, 'src/generated'), { recursive: true });
  for (const k of Object.keys(manifest)) manifest[k].sort((a, b) => a.w - b.w);
  const rows = Object.entries(manifest)
    .map(([k, v]) => `  '${k}': [\n${v.map((x) => `    { w: ${x.w}, h: ${x.h}, src: '${x.src}' },`).join('\n')}\n  ],`)
    .join('\n');
  const body = `// Generated by scripts/generate-assets.mjs — do not edit.\nexport const images = {\n${rows}\n};\n`;
  await writeFile(path.join(root, 'src/generated/images.js'), body);
}

/* ---------- text helpers ---------- */
function textPath(font, text, cx, baseline, size, fill, letterSpacing = 0) {
  const chars = [...text];
  const glyphW = font.getAdvanceWidth(text, size);
  const total = glyphW + letterSpacing * (chars.length - 1);
  let x = cx - total / 2;
  if (!letterSpacing) {
    return `<path fill="${fill}" d="${font.getPath(text, x, baseline, size).toPathData(2)}"/>`;
  }
  let d = '';
  for (const ch of chars) {
    // one <path> per glyph: some glyph outlines don't close their last
    // contour, which breaks rendering when concatenated
    const glyph = font.getPath(ch, x, baseline, size).toPathData(2);
    if (glyph) d += `<path d="${glyph}"/>`;
    x += font.getAdvanceWidth(ch, size) + letterSpacing;
  }
  return `<g fill="${fill}">${d}</g>`;
}

function divider(cx, y, w, color) {
  const h = w / 2;
  return `<g stroke="${color}" stroke-width="1.4" fill="none">
    <line x1="${cx - h}" y1="${y}" x2="${cx - 14}" y2="${y}"/>
    <line x1="${cx + 14}" y1="${y}" x2="${cx + h}" y2="${y}"/>
    <path d="M${cx} ${y - 8} L${cx + 8} ${y} L${cx} ${y + 8} L${cx - 8} ${y} Z" fill="${color}"/>
    <circle cx="${cx - h}" cy="${y}" r="2.2" fill="${color}"/>
    <circle cx="${cx + h}" cy="${y}" r="2.2" fill="${color}"/>
  </g>`;
}

/* ---------- OG image ---------- */
async function ogImage(script, caps) {
  const W = 1200;
  const H = 630;
  const photoSrc = srcImg('couple/couple-arch.webp');

  const bg = await sharp(photoSrc)
    .resize(W, H, { fit: 'cover', position: 'centre' })
    .blur(28)
    .toBuffer();

  const overlay = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">
    <defs>
      <linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
        <stop offset="0" stop-color="#0F3D2E" stop-opacity=".9"/>
        <stop offset=".5" stop-color="#2A1715" stop-opacity=".82"/>
        <stop offset="1" stop-color="#4A1F2E" stop-opacity=".9"/>
      </linearGradient>
    </defs>
    <rect width="${W}" height="${H}" fill="url(#g)"/>
  </svg>`;

  // Arch-framed photo in the centre
  const pw = 330;
  const ph = 500;
  const px = (W - pw) / 2;
  const py = 70;
  const s = pw / 300;
  const archH = ph / s;
  const clip = archPath({ W: 300, topH: 124, bottom: archH, closed: true, sx: s, sy: s }).d;
  const photo = await sharp(photoSrc).resize(pw, ph, { fit: 'cover', position: 'centre' }).toBuffer();
  const mask = Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${pw}" height="${ph}"><path d="${clip}" fill="#fff"/></svg>`,
  );
  const archPhoto = await sharp(photo).composite([{ input: mask, blend: 'dest-in' }]).png().toBuffer();

  const outer = archPath({ W: 300, topH: 124, bottom: archH, sx: s, sy: s }).d;
  const inner = archPath({ W: 300, topH: 124, bottom: archH - 7, inset: 7, sx: s, sy: s }).d;
  const leftCx = px / 2;
  const rightCx = W - px / 2;
  const text = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}">
    <g transform="translate(${px} ${py})" fill="none">
      <path d="${outer}" stroke="${GOLD}" stroke-width="5" transform="translate(0 0)"/>
      <path d="${inner}" stroke="${GOLD_LIGHT}" stroke-width="1.6" stroke-opacity=".9"/>
      <rect x="-5" y="${ph - 2}" width="${pw + 10}" height="0" />
    </g>
    <line x1="${px - 2.5}" y1="${py + ph}" x2="${px + pw + 2.5}" y2="${py + ph}" stroke="${GOLD}" stroke-width="5"/>
    ${textPath(caps, 'THE BRIDE', leftCx, 228, 20, BLUSH, 5)}
    ${textPath(script, content.couple.bride, leftCx, 330, 104, GOLD_LIGHT)}
    ${divider(leftCx, 378, 220, GOLD)}
    ${textPath(caps, '15 – 16 JANUARY 2027', leftCx, 428, 21, IVORY, 2.5)}
    ${textPath(caps, 'THE GROOM', rightCx, 228, 20, BLUSH, 5)}
    ${textPath(script, content.couple.groom, rightCx, 330, 104, GOLD_LIGHT)}
    ${divider(rightCx, 378, 220, GOLD)}
    ${textPath(caps, 'JAIPUR · RAJASTHAN', rightCx, 428, 21, IVORY, 2.5)}
  </svg>`;

  await sharp(bg)
    .composite([
      { input: Buffer.from(overlay) },
      { input: archPhoto, left: px, top: py },
      { input: Buffer.from(text) },
    ])
    .jpeg({ quality: 84, mozjpeg: true })
    .toFile(pub('og-image.jpg'));
}

/* ---------- favicon ---------- */
async function favicon(script, caps) {
  const S = 64;
  // Lay out "T & U" centred: capitals in Cinzel, ampersand smaller
  const big = 25;
  const small = 15;
  const gap = 1.5;
  const wT = caps.getAdvanceWidth('T', big);
  const wA = caps.getAdvanceWidth('&', small);
  const wU = caps.getAdvanceWidth('U', big);
  let x = (S - (wT + wA + wU + gap * 2)) / 2;
  const T = caps.getPath('T', x, 41, big).toPathData(2);
  x += wT + gap;
  const amp = caps.getPath('&', x, 40, small).toPathData(2);
  x += wA + gap;
  const U = caps.getPath('U', x, 41, big).toPathData(2);
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}">
<rect x="1" y="1" width="62" height="62" rx="14" fill="${IVORY}" stroke="#B08D57" stroke-width="2"/>
<rect x="5" y="5" width="54" height="54" rx="10.5" fill="none" stroke="${GOLD}" stroke-width=".8"/>
<path fill="#A07A3E" d="${T}"/><path fill="#A07A3E" d="${U}"/>
<path fill="#C2185B" d="${amp}"/>
</svg>
`;
  await writeFile(pub('favicon.svg'), svg);
  await sharp(Buffer.from(svg), { density: 600 }).resize(180, 180).png().toFile(pub('apple-touch-icon.png'));
}

/* ---------- the family's own artwork (assets/art) ---------- */
// Used as-is. Files are only re-encoded if they exceed the 300 KB budget,
// and the paper-garden artwork is cut into its separate elements.
async function art() {
  const out = (...p) => pub('images/art', ...p);
  await rm(pub('images/texture'), { recursive: true, force: true });
  await rm(out(), { recursive: true, force: true });
  await mkdir(out(), { recursive: true });
  const src = (f) => path.join(root, 'assets/art', f);
  for (const f of ['hero-arch.jpg', 'lotus-emboss.webp', 'lantern-arch.webp', 'lotus-border.jpg']) {
    const { size } = await stat(src(f));
    if (size <= 300 * 1024) {
      await writeFile(out(f), await readFile(src(f)));
    } else {
      await sharp(src(f)).webp({ quality: 82 }).toFile(out(f));
    }
  }
  // Woven canvas from inside the Mughal arch, mirrored 2x2 into a seamless tile
  {
    // high-pass: keep the weave, drop the faint paisley so mirroring shows no pattern
    const crop = sharp(src('mughal-arch.webp')).extract({ left: 230, top: 760, width: 660, height: 490 }).removeAlpha();
    const { data, info } = await crop.clone().raw().toBuffer({ resolveWithObject: true });
    const low = await crop.clone().blur(18).raw().toBuffer();
    const mean = [235, 233, 228];
    const hp = Buffer.alloc(data.length);
    for (let i = 0; i < data.length; i++) hp[i] = Math.max(0, Math.min(255, data[i] - low[i] + mean[i % 3]));
    // seamless tile by cross-fading opposite edges (no mirroring, so the weave stays natural)
    const B = 70;
    const W0 = info.width;
    const H0 = info.height;
    const TW = W0 - B;
    const TH = H0 - B;
    const px = (x, y, k) => hp[(y * W0 + x) * 3 + k];
    const tile = Buffer.alloc(TW * TH * 3);
    for (let y = 0; y < TH; y++) {
      for (let x = 0; x < TW; x++) {
        const ax = x < B ? x / B : 1; // weight of the main pixel vs. its wrap partner
        const ay = y < B ? y / B : 1;
        for (let k = 0; k < 3; k++) {
          const v00 = px(x, y, k);
          const v10 = x < B ? px(x + TW, y, k) : v00;
          const v01 = y < B ? px(x, y + TH, k) : v00;
          const v11 = x < B && y < B ? px(x + TW, y + TH, k) : x < B ? v10 : v01;
          const top = v00 * ax + v10 * (1 - ax);
          const bot = v01 * ax + v11 * (1 - ax);
          tile[(y * TW + x) * 3 + k] = Math.round(top * ay + bot * (1 - ay));
        }
      }
    }
    await sharp(tile, { raw: { width: TW, height: TH, channels: 3 } }).webp({ quality: 72 }).toFile(out('canvas.webp'));
  }
  const paper = src('paper-garden.webp');
  // cut the drawn elements out of the paper (colour key on the paper tone)
  const cutout = async (region, file) => {
    const { data, info } = await sharp(paper).extract(region).removeAlpha().raw().toBuffer({ resolveWithObject: true });
    const rgba = Buffer.alloc(info.width * info.height * 4);
    for (let i = 0, j = 0; i < data.length; i += 3, j += 4) {
      // distance to the paper's tone range, light (249,241,221) to warm (236,220,184)
      const A = [249, 241, 221];
      const D = [-13, -21, -37];
      const v = [data[i] - A[0], data[i + 1] - A[1], data[i + 2] - A[2]];
      const t = Math.max(0, Math.min(1, (v[0] * D[0] + v[1] * D[1] + v[2] * D[2]) / (D[0] ** 2 + D[1] ** 2 + D[2] ** 2)));
      const d = Math.hypot(v[0] - t * D[0], v[1] - t * D[1], v[2] - t * D[2]);
      rgba[j] = data[i];
      rgba[j + 1] = data[i + 1];
      rgba[j + 2] = data[i + 2];
      rgba[j + 3] = Math.max(0, Math.min(255, Math.round(((d - 13) / 26) * 255)));
    }
    await sharp(rgba, { raw: { width: info.width, height: info.height, channels: 4 } }).webp({ quality: 84, alphaQuality: 90 }).toFile(out(file));
  };
  await cutout({ left: 650, top: 280, width: 475, height: 500 }, 'banana-flower.webp');
  await cutout({ left: 0, top: 1040, width: 1125, height: 960 }, 'garden-strip.webp');
}

const [script, caps] = await Promise.all([
  loadFont('PinyonScript-Regular.ttf'),
  loadFont('Cinzel-Medium.ttf'),
]);
await variants();
await hero();
await art();
await writeManifest();
await ogImage(script, caps);
await favicon(script, caps);
console.log('Assets generated in public/');
